# Generates the arena world so wall/box geometry stays consistent.
#   python3 tools/gen_world.py pushbot_gazebo/worlds/arena.sdf
#   python3 tools/gen_world.py pushbot_gazebo/worlds/arena_empty.sdf --empty
# Box size, mass and friction are the defaults of push_box() below.
L, W, H, T = 8.0, 6.0, 0.5, 0.15   # interior length (x), width (y), wall height, thickness

def static_box(name, x, y, sx, sy, sz, rgb="0.7 0.7 0.7", yaw=0.0):
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{x} {y} {sz/2} 0 0 {yaw}</pose>
      <link name="link">
        <collision name="collision"><geometry><box><size>{sx} {sy} {sz}</size></box></geometry></collision>
        <visual name="visual">
          <geometry><box><size>{sx} {sy} {sz}</size></box></geometry>
          <material><ambient>{rgb} 1</ambient><diffuse>{rgb} 1</diffuse></material>
        </visual>
      </link>
    </model>"""

def push_box(name, x, y, s=0.25, m=0.4, mu=0.4):
    i = m * (s*s + s*s) / 12.0
    return f"""
    <model name="{name}">
      <pose>{x} {y} {s/2} 0 0 0</pose>
      <link name="link">
        <inertial>
          <mass>{m}</mass>
          <inertia><ixx>{i:.6f}</ixx><iyy>{i:.6f}</iyy><izz>{i:.6f}</izz><ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia>
        </inertial>
        <collision name="collision">
          <geometry><box><size>{s} {s} {s}</size></box></geometry>
          <surface><friction><ode><mu>{mu}</mu><mu2>{mu}</mu2></ode></friction></surface>
        </collision>
        <visual name="visual">
          <geometry><box><size>{s} {s} {s}</size></box></geometry>
          <material><ambient>0.8 0.1 0.1 1</ambient><diffuse>0.8 0.1 0.1 1</diffuse></material>
        </visual>
      </link>
    </model>"""

walls = "".join([
    static_box("wall_north",  0,  W/2 + T/2, L + 2*T, T, H),
    static_box("wall_south",  0, -W/2 - T/2, L + 2*T, T, H),
    static_box("wall_east",   L/2 + T/2, 0, T, W, H),
    static_box("wall_west",  -L/2 - T/2, 0, T, W, H),
    # interior features: give SLAM something to recognise and Nav2 something to plan around
    static_box("divider",    -0.5, 1.75, T, 2.5, H, "0.55 0.55 0.6"),
    static_box("pillar",      1.8, -1.0, 0.4, 0.4, H, "0.55 0.55 0.6"),
    static_box("ledge",      -2.5, -2.0, 1.2, T, H, "0.55 0.55 0.6"),
])

boxes = "".join([
    push_box("box_1", -1.5, -0.5),
    push_box("box_2",  0.8,  0.6),
    push_box("box_3",  0.2, -2.0),
])

goal = """
    <!-- Goal zone: a visual-only green square (no collision, so the robot and LiDAR ignore it) -->
    <model name="goal_zone">
      <static>true</static>
      <pose>3.2 2.2 0.001 0 0 0</pose>
      <link name="link">
        <visual name="visual">
          <geometry><box><size>1.2 1.2 0.002</size></box></geometry>
          <material><ambient>0.1 0.7 0.2 1</ambient><diffuse>0.1 0.7 0.2 1</diffuse></material>
        </visual>
      </link>
    </model>"""

sdf = f"""<?xml version="1.0"?>
<!--
  PDE4430 arena: {L:.0f} m x {W:.0f} m walled area with a divider, a pillar, a ledge,
  three pushable red boxes and a green goal zone in the north-east corner.
  Generated by tools/gen_world.py - edit that script rather than this file.
-->
<sdf version="1.9">
  <world name="arena">

    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>

    <!-- Core systems. Sensors (with a render engine) is required for the gpu_lidar. -->
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>

    <scene>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.8 0.85 0.9 1</background>
      <grid>false</grid>
    </scene>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.4 0.2 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry>
          <material><ambient>0.85 0.85 0.8 1</ambient><diffuse>0.85 0.85 0.8 1</diffuse></material>
        </visual>
      </link>
    </model>
{walls}
{goal}
{boxes}
  </world>
</sdf>
"""
import sys
# Usage: gen_world.py <out.sdf> [--empty]   (--empty leaves out the boxes, for mapping)
empty = "--empty" in sys.argv
if empty:
    sdf = sdf.replace(boxes, "\n    <!-- No boxes: this version is for mapping with SLAM -->")
open(sys.argv[1], "w").write(sdf)
